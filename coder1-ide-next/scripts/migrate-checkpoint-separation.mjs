#!/usr/bin/env node
/**
 * Checkpoint Type Separation Migration
 * 
 * Migrates checkpoint storage to separate manual and auto checkpoints:
 * 1. Adds 'type' column to database (manual | auto)
 * 2. Organizes file system into manual/ and auto/ subdirectories
 * 3. Updates all existing checkpoints (currently all manual)
 * 
 * Safe to run multiple times (idempotent)
 */

import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { readdir, mkdir, rename, access, readFile } from 'fs/promises';
import BetterSqlite3 from 'better-sqlite3';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const projectRoot = join(__dirname, '..');

// Database setup
const dbPath = join(projectRoot, 'db', 'context-memory.db');
let db;

async function migrateDatabase() {
  console.log('\n📊 Step 1: Migrating Database Schema\n');
  
  try {
    db = new BetterSqlite3(dbPath);
    
    // Check if type column already exists
    const tableInfo = db.prepare("PRAGMA table_info(checkpoints)").all();
    const hasTypeColumn = tableInfo.some(col => col.name === 'type');
    
    if (hasTypeColumn) {
      console.log('  ✅ Database already has type column');
    } else {
      // Add type column
      db.prepare("ALTER TABLE checkpoints ADD COLUMN type TEXT DEFAULT 'manual'").run();
      console.log('  ✅ Added type column to checkpoints table');
      
      // Update existing rows to 'manual' (all existing checkpoints are manual)
      const result = db.prepare("UPDATE checkpoints SET type = 'manual' WHERE type IS NULL").run();
      console.log(`  ✅ Updated ${result.changes} existing checkpoints to type='manual'`);
    }
    
    // Create index for performance
    try {
      db.prepare('CREATE INDEX IF NOT EXISTS idx_checkpoints_type ON checkpoints(type)').run();
      console.log('  ✅ Created index on type column');
    } catch (err) {
      if (!err.message.includes('already exists')) {
        throw err;
      }
      console.log('  ✅ Index already exists');
    }
    
    // Verify migration
    const stats = db.prepare(`
      SELECT type, COUNT(*) as count 
      FROM checkpoints 
      GROUP BY type
    `).all();
    
    console.log('\n  📈 Database checkpoint counts:');
    stats.forEach(({ type, count }) => {
      console.log(`     ${type}: ${count} checkpoints`);
    });
    
  } catch (error) {
    console.error('  ❌ Database migration failed:', error);
    throw error;
  } finally {
    if (db) {
      db.close();
    }
  }
}

async function migrateFileSystem() {
  console.log('\n📁 Step 2: Organizing File System\n');
  
  const sessionsDir = join(projectRoot, 'data', 'sessions');
  
  try {
    const sessions = await readdir(sessionsDir);
    console.log(`  Found ${sessions.length} sessions to process\n`);
    
    let totalMoved = 0;
    let totalSkipped = 0;
    
    for (const sessionDir of sessions) {
      const checkpointsDir = join(sessionsDir, sessionDir, 'checkpoints');
      
      try {
        // Check if checkpoints directory exists
        await access(checkpointsDir);
        
        // Create manual and auto subdirectories
        const manualDir = join(checkpointsDir, 'manual');
        const autoDir = join(checkpointsDir, 'auto');
        
        await mkdir(manualDir, { recursive: true });
        await mkdir(autoDir, { recursive: true });
        
        // Read all checkpoint files in root
        const files = await readdir(checkpointsDir);
        const checkpointFiles = files.filter(f => f.endsWith('.json') && f.startsWith('checkpoint_'));
        
        if (checkpointFiles.length === 0) {
          totalSkipped++;
          continue;
        }
        
        console.log(`  📦 Session: ${sessionDir}`);
        
        for (const file of checkpointFiles) {
          const oldPath = join(checkpointsDir, file);
          
          // Read checkpoint to determine type
          const content = await readFile(oldPath, 'utf-8');
          const checkpoint = JSON.parse(content);
          
          // Determine type (all existing checkpoints are manual since auto isn't implemented yet)
          const type = checkpoint.autoGenerated ? 'auto' : 'manual';
          const newPath = join(checkpointsDir, type, file);
          
          // Move file
          await rename(oldPath, newPath);
          totalMoved++;
          console.log(`     ✅ Moved ${file} → ${type}/`);
        }
        
      } catch (error) {
        if (error.code === 'ENOENT') {
          // Checkpoints directory doesn't exist for this session
          totalSkipped++;
          continue;
        }
        console.error(`     ❌ Error processing session ${sessionDir}:`, error.message);
      }
    }
    
    console.log(`\n  📊 Migration Summary:`);
    console.log(`     Sessions processed: ${sessions.length}`);
    console.log(`     Checkpoints moved: ${totalMoved}`);
    console.log(`     Sessions skipped: ${totalSkipped}`);
    
  } catch (error) {
    console.error('  ❌ File system migration failed:', error);
    throw error;
  }
}

async function verifyMigration() {
  console.log('\n✅ Step 3: Verifying Migration\n');
  
  const sessionsDir = join(projectRoot, 'data', 'sessions');
  
  try {
    const sessions = await readdir(sessionsDir);
    let manualCount = 0;
    let autoCount = 0;
    let legacyCount = 0;
    
    for (const sessionDir of sessions) {
      const checkpointsDir = join(sessionsDir, sessionDir, 'checkpoints');
      
      try {
        // Count manual checkpoints
        try {
          const manualFiles = await readdir(join(checkpointsDir, 'manual'));
          manualCount += manualFiles.filter(f => f.endsWith('.json')).length;
        } catch (err) {
          // manual directory doesn't exist
        }
        
        // Count auto checkpoints
        try {
          const autoFiles = await readdir(join(checkpointsDir, 'auto'));
          autoCount += autoFiles.filter(f => f.endsWith('.json')).length;
        } catch (err) {
          // auto directory doesn't exist
        }
        
        // Count legacy checkpoints (not yet migrated)
        try {
          const rootFiles = await readdir(checkpointsDir);
          legacyCount += rootFiles.filter(f => f.endsWith('.json') && f.startsWith('checkpoint_')).length;
        } catch (err) {
          // checkpoints directory doesn't exist
        }
        
      } catch (error) {
        // Session doesn't have checkpoints
      }
    }
    
    console.log('  📊 File System Verification:');
    console.log(`     Manual checkpoints: ${manualCount}`);
    console.log(`     Auto checkpoints: ${autoCount}`);
    console.log(`     Legacy (unmigrated): ${legacyCount}`);
    
    if (legacyCount > 0) {
      console.log('\n  ⚠️  Warning: Some checkpoints were not migrated');
      console.log('     Run this script again to complete migration');
    } else {
      console.log('\n  ✅ All checkpoints successfully migrated!');
    }
    
  } catch (error) {
    console.error('  ❌ Verification failed:', error);
  }
}

async function main() {
  console.log('╔════════════════════════════════════════════════════════╗');
  console.log('║   Checkpoint Type Separation Migration                ║');
  console.log('╚════════════════════════════════════════════════════════╝');
  
  try {
    await migrateDatabase();
    await migrateFileSystem();
    await verifyMigration();
    
    console.log('\n✅ Migration complete!\n');
    console.log('Next steps:');
    console.log('  1. Restart the development server');
    console.log('  2. Test checkpoint creation (both manual and auto)');
    console.log('  3. Verify Sessions panel shows manual checkpoints');
    console.log('  4. Verify Timeline shows both types\n');
    
  } catch (error) {
    console.error('\n❌ Migration failed:', error);
    process.exit(1);
  }
}

main();
