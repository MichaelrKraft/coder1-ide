// Generate checkpoint name with custom name support
const generateCheckpointName = (customName?: string, autoGenerated?: boolean): string => {
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-US');
  const timeStr = now.toLocaleTimeString();
  
  if (customName && customName.trim()) {
    return `${customName.trim()} - ${dateStr} ${timeStr}`;
  }
  
  if (autoGenerated) {
    return `Auto-checkpoint ${dateStr} ${timeStr}`;
  }
  
  return `Checkpoint ${dateStr} ${timeStr}`;
};

// Get the correct data directory path
const getDataDirectory = () => {
  // The server runs from /autonomous_vibe_interface/coder1-ide-next, so data is in ./data
  const projectRoot = process.cwd();
  const dataDir = path.join(projectRoot, 'data');
  
  console.log('📂 Checkpoint API - Project root:', projectRoot);
  console.log('📂 Checkpoint API - Data directory:', dataDir);
  
  return dataDir;
};

// Helper: Read checkpoints from manual/, auto/, and legacy root directories
const readCheckpointsFromAllLocations = async (checkpointsBaseDir: string) => {
  const checkpoints: any[] = [];
  
  // Try reading from type-specific subdirectories (manual/ and auto/)
  for (const type of ['manual', 'auto']) {
    const typeDir = path.join(checkpointsBaseDir, type);
    try {
      const files = await fs.readdir(typeDir);
      const jsonFiles = files.filter(f => f.endsWith('.json'));
      
      const readPromises = jsonFiles.map(async (file) => {
        const content = await fs.readFile(path.join(typeDir, file), 'utf8');
        const checkpoint = JSON.parse(content);
        // Ensure checkpoint has type field for consistency
        if (!checkpoint.type) checkpoint.type = type;
        return checkpoint;
      });
      
      const typeCheckpoints = await Promise.all(readPromises);
      checkpoints.push(...typeCheckpoints);
    } catch (error) {
      // Directory doesn't exist yet - normal for new installations or pre-migration
    }
  }
  
  // BACKWARD COMPATIBILITY: Also check root checkpoints directory for legacy checkpoints
  try {
    const rootFiles = await fs.readdir(checkpointsBaseDir);
    const jsonFiles = rootFiles.filter(f => f.endsWith('.json') && f.startsWith('checkpoint_'));
    
    if (jsonFiles.length > 0) {
      const readPromises = jsonFiles.map(async (file) => {
        const content = await fs.readFile(path.join(checkpointsBaseDir, file), 'utf8');
        const checkpoint = JSON.parse(content);
        // Legacy checkpoints are assumed to be manual
        if (!checkpoint.type) checkpoint.type = 'manual';
        return checkpoint;
      });
      
      const legacyCheckpoints = await Promise.all(readPromises);
      checkpoints.push(...legacyCheckpoints);
    }
  } catch (error) {
    // Root directory doesn't exist or has no JSON files
  }
  
  return checkpoints;
};

// Self-contained checkpoint storage
export async function POST(request: NextRequest) {
  try {
    const data = await request.json();
    
    // Get or create sessionId
    const sessionId = data.sessionId || `session_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`;
    const checkpointId = `checkpoint_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`;
    
    // Determine checkpoint type (manual or auto)
    const checkpointType = data.autoGenerated ? 'auto' : 'manual';
    
    // Ensure data directory structure exists with type subdirectories
    const dataDir = getDataDirectory();
    const sessionDir = path.join(dataDir, 'sessions', sessionId);
    const checkpointsDir = path.join(sessionDir, 'checkpoints', checkpointType);
    
    console.log(`📂 POST - Creating ${checkpointType} checkpoint in directory:`, checkpointsDir);
    
    await fs.mkdir(checkpointsDir, { recursive: true });
    
    // Create session metadata if it doesn't exist
    const sessionMetadataPath = path.join(sessionDir, 'metadata.json');
    const now = new Date();
    
    try {
      await fs.access(sessionMetadataPath);
    } catch {
      // Session metadata doesn't exist, create it with intelligent naming
      const hour = now.getHours();
      const timeOfDay = hour < 6 ? 'Late Night' : 
                       hour < 12 ? 'Morning' : 
                       hour < 17 ? 'Afternoon' : 
                       hour < 21 ? 'Evening' : 'Night';
      
      const timeStr = now.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });
      const dateStr = now.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
      
      const sessionMetadata = {
        id: sessionId,
        name: `💻 ${timeOfDay} Coding Session - ${dateStr} ${timeStr}`,
        description: `Coder1 IDE ${timeOfDay.toLowerCase()} development session`,
        createdAt: now.toISOString(),
        lastUpdated: now.toISOString()
      };
      await fs.writeFile(sessionMetadataPath, JSON.stringify(sessionMetadata, null, 2));
    }
    
    // ALWAYS ensure session exists in database (moved outside metadata check)
    // This fixes the issue where existing sessions never get database records
    try {
      const currentProjectPath = process.cwd();
      const folder = await contextDatabase.getOrCreateFolder(currentProjectPath);
      
      // Check if session exists in database
      const db = await getDatabase();
      const existingSession = db.prepare('SELECT id FROM context_sessions WHERE id = ?').get(sessionId);
      
      if (!existingSession) {
        // Session doesn't exist in database - create it now
        db.prepare(`
          INSERT INTO context_sessions (id, folder_id, start_time)
          VALUES (?, ?, ?)
        `).run(sessionId, folder.id, now.toISOString());
        console.log(`✅ Created session in database: ${sessionId}`);
      } else {
        console.log(`ℹ️ Session already exists in database: ${sessionId}`);
      }
      
      closeDatabaseSafely(db);
    } catch (dbError) {
      console.warn('⚠️ Could not create session in database:', dbError);
      // Continue anyway - checkpoint will still save to JSON
    }
    
    // ENHANCED: Query conversation history from context database BEFORE creating checkpoint
    let conversationHistory: any[] = [];
    try {
      // Get recent conversations for this terminal session/project
      const currentProjectPath = process.cwd();
      
      // Try to get context folder and recent conversations
      // Wrap in additional safety check for database availability
      if (contextDatabase && typeof contextDatabase.getOrCreateFolder === 'function') {
        try {
          const folder = await contextDatabase.getOrCreateFolder(currentProjectPath);
          if (folder) {
            // Get recent conversations from this folder (across all sessions)
            conversationHistory = await contextDatabase.getRecentConversations(folder.id, 10);
            console.log(`📊 Enhanced checkpoint: Found ${conversationHistory.length} recent conversations`);
          }
        } catch (dbError) {
          console.warn('⚠️ Context database error, continuing without conversation history:', dbError);
        }
      } else {
        console.log('ℹ️ Context database not available, checkpoint will save without conversation history');
      }
    } catch (error) {
      console.warn('⚠️ Could not retrieve conversation history for checkpoint:', (error as Error).message);
      // Continue without conversation history - don't fail the checkpoint creation
    }

    // Filter snapshot data to remove thinking animations and artifacts
    const filteredSnapshot = processCheckpointDataForSave(data.snapshot);
    
    // 🛟 SESSION RESCUE: Get current git branch for recovery tracking
    let currentGitBranch: string | undefined;
    try {
      const { stdout } = await execAsync('git rev-parse --abbrev-ref HEAD');
      currentGitBranch = stdout.trim();
    } catch (error) {
      // Not in a git repo or git not available - not critical for checkpoint
      console.log('ℹ️ Could not detect git branch (not a git repo or git unavailable)');
    }
    
    // Extract terminal history from request data and filter out status lines ASYNCHRONOUSLY
    let rawTerminalHistory = data.terminalHistory || data.snapshot?.terminal || '';
    
    // 🔍 DEBUG: Log terminal history source and length
    const historySource = data.terminalHistory ? 'data.terminalHistory' : 
                          data.snapshot?.terminal ? 'data.snapshot.terminal' : 
                          'empty (no source)';
    console.log(`📊 CHECKPOINT DEBUG: Terminal history source: ${historySource}`);
    console.log(`📊 CHECKPOINT DEBUG: Raw terminal history length: ${rawTerminalHistory.length} characters`);
    
    // 🔒 SIZE LIMIT: Truncate terminal history if too large (prevents freeze bug)
    const originalSize = Buffer.byteLength(rawTerminalHistory, 'utf8');
    if (originalSize > MAX_TERMINAL_HISTORY_SIZE) {
      rawTerminalHistory = truncateTerminalHistory(rawTerminalHistory);
      console.log(`✂️ Truncated oversized terminal history to prevent page freeze`);
    }
    
    // Skip checkpoint creation if terminal history is empty or too small (manual checkpoints only)
    // Auto-generated checkpoints are allowed with minimal terminal history since they
    // capture file/editor state regardless of terminal activity
    if (!data.autoGenerated && rawTerminalHistory.length < 100) {
      console.log(`⏭️ Skipping checkpoint creation: Terminal history too small (${rawTerminalHistory.length} chars < 100 chars minimum)`);
      return NextResponse.json({
        success: false,
        skipped: true,
        reason: 'Terminal history too small',
        message: 'Checkpoint not created: Terminal history must have at least 100 characters'
      });
    }
    
    console.log(`🔄 Starting async filtering of ${rawTerminalHistory.length} characters...`);
    const filterStartTime = Date.now();
    const terminalHistory = await filterThinkingAnimationsAsync(rawTerminalHistory);
    const filterDuration = Date.now() - filterStartTime;
    console.log(`✅ Async filtering complete in ${filterDuration}ms: ${rawTerminalHistory.length} → ${terminalHistory.length} characters`);
    
    // 🚨 CRITICAL: Store the SAME filtered string in both places to prevent double filtering
    // Using the same reference prevents corruption from multiple filter passes
    const checkpoint = {
      id: checkpointId,
      sessionId,
      name: generateCheckpointName(data.customName, data.autoGenerated),
      description: data.autoGenerated ? 'Auto-generated checkpoint from IDE' : 'Manual checkpoint from IDE',
      timestamp: new Date().toISOString(),
      terminalHistory: terminalHistory,  // ← Same filtered string
      data: {
        timestamp: data.timestamp,
        activeFile: data.activeFile,
        snapshot: filteredSnapshot,  // ← Filtered to remove thinking animations
        conversationHistory: conversationHistory,  // ← Enhanced with conversation data
        terminalHistory: terminalHistory  // ← Same filtered string (not re-filtered!)
      },
      tags: ['ide', data.autoGenerated ? 'auto' : 'manual'],
      autoGenerated: data.autoGenerated || false,
      // 🛟 SESSION RESCUE: Recovery metadata
      type: checkpointType,
      checkpointType: checkpointType,  // Alias for clarity
      gitBranch: currentGitBranch,
      openFiles: extractFilePaths(filteredSnapshot.files),
      claudeContext: conversationHistory.length > 0 ? {
        messages: conversationHistory,
        hasActiveTask: false  // Could be enhanced with actual task detection
      } : undefined
    };
    
    // 🛟 Calculate recovery score and recoverability
    const recoveryScore = calculateRecoveryScore({
      id: checkpoint.id,
      sessionId: checkpoint.sessionId,
      timestamp: new Date(checkpoint.timestamp).getTime(),
      openFiles: checkpoint.openFiles,
      terminalHistory: checkpoint.terminalHistory,
      claudeContext: checkpoint.claudeContext,
      gitBranch: checkpoint.gitBranch,
      checkpointType: checkpoint.checkpointType
    }, currentGitBranch);
    
    // Add recovery metadata
    (checkpoint as any).recoveryScore = recoveryScore.overall;
    (checkpoint as any).isRecoverable = isCheckpointRecoverable({
      id: checkpoint.id,
      sessionId: checkpoint.sessionId,
      timestamp: new Date(checkpoint.timestamp).getTime(),
      openFiles: checkpoint.openFiles,
      terminalHistory: checkpoint.terminalHistory,
      claudeContext: checkpoint.claudeContext,
      gitBranch: checkpoint.gitBranch,
      checkpointType: checkpoint.checkpointType
    });
    (checkpoint as any).recoveryWarnings = recoveryScore.warnings;
    
    console.log(`🛟 Recovery Score: ${recoveryScore.overall}/100 (Recoverable: ${(checkpoint as any).isRecoverable})`);
    
    // Save enhanced checkpoint to JSON file (Phase 1: Keep JSON files)
    const checkpointPath = path.join(checkpointsDir, `${checkpointId}.json`);
    await fs.writeFile(checkpointPath, JSON.stringify(checkpoint, null, 2));

    // 🔄 DUAL-WRITE: Also save to database (Phase 1: Parallel storage)
    try {
      const db = await getDatabase();
      
      // Prepare metadata JSON
      const metadataJson = JSON.stringify({
        tags: checkpoint.tags,
        autoGenerated: checkpoint.autoGenerated,
        activeFile: checkpoint.data?.activeFile,
        conversationHistory: checkpoint.data?.conversationHistory
      });
      
      // Prepare files snapshot JSON
      const filesJson = JSON.stringify(checkpoint.data?.snapshot || {});
      
      // Insert into database with type column
      const stmt = db.prepare(`
        INSERT INTO checkpoints (
          id, session_id, name, description, timestamp,
          terminal_history, terminal_history_size, files_snapshot, metadata, type
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
      `);
      
      stmt.run(
        checkpoint.id,
        checkpoint.sessionId,
        checkpoint.name,
        checkpoint.description,
        checkpoint.timestamp,
        terminalHistory,  // Store filtered terminal history
        terminalHistory.length,  // Store size for queries
        filesJson,
        metadataJson,
        checkpointType  // Add type (manual or auto)
      );
      
      closeDatabaseSafely(db);
      console.log(`✅ Checkpoint saved to database: ${checkpointId} (${terminalHistory.length} chars terminal history)`);
    } catch (dbError) {
      // Don't fail the checkpoint if database write fails - JSON file is primary
      console.error('⚠️ Failed to save checkpoint to database (JSON file saved successfully):', dbError);
    }

    // Update session metadata
    const sessionData = JSON.parse(await fs.readFile(sessionMetadataPath, 'utf8'));
    sessionData.lastUpdated = new Date().toISOString();
    await fs.writeFile(sessionMetadataPath, JSON.stringify(sessionData, null, 2));

    // Async session memory indexing - don't block checkpoint response
    setImmediate(async () => {
      try {
        const { indexSessionFromCheckpoint } = await import('@/services/memory/session-indexer');
        const indexResult = await indexSessionFromCheckpoint(checkpoint, sessionId, 'default');
        console.log(`[SessionIndexer] Indexed ${indexResult.chunksIndexed} chunks, skipped ${indexResult.skipped}`);
      } catch (indexError) {
        console.error('[SessionIndexer] Indexing failed (non-blocking):', indexError);
      }
    });

    return NextResponse.json({
      success: true,
      checkpoint,
      sessionId
    });
    
  } catch (error) {
    console.error('Checkpoint API error:', error);
    return NextResponse.json(
      { error: 'Failed to create checkpoint' },
      { status: 500 }
    );
  }
}

export async function GET(request: NextRequest) {
  try {
    const { searchParams } = new URL(request.url);
    const sessionId = searchParams.get('sessionId');
    
    const dataDir = getDataDirectory();
    const sessionsDir = path.join(dataDir, 'sessions');
    
    console.log('📂 GET - Looking for sessions in directory:', sessionsDir);
    console.log('📂 GET - Requested sessionId:', sessionId);
    
    if (!sessionId) {
      // If no sessionId, find the latest session
      try {
        const sessions = await fs.readdir(sessionsDir);
        if (sessions.length > 0) {
          // Get the most recent session by extracting timestamp from session ID
          // Session IDs are like: session_1764136829642_pf9dgiyq6wq
          const latestSession = sessions
            .filter(s => s.startsWith('session_'))
            .map(s => {
              const match = s.match(/session_(\d+)_/);
              return {
                name: s,
                timestamp: match ? parseInt(match[1]) : 0
              };
            })
            .sort((a, b) => b.timestamp - a.timestamp)[0]?.name;
          const checkpointsBaseDir = path.join(sessionsDir, latestSession!, 'checkpoints');
          
          try {
            // Read from both manual/ and auto/ subdirectories + legacy root
            const checkpoints = await readCheckpointsFromAllLocations(checkpointsBaseDir);
            console.log(`📊 Performance: Loaded ${checkpoints.length} checkpoints from all locations`);
            
            // Sort by timestamp (newest first)
            checkpoints.sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime());
            
            return NextResponse.json({ 
              success: true,
              checkpoints,
              sessionId: latestSession
            });
          } catch {
            return NextResponse.json({ 
              success: true,
              checkpoints: [],
              sessionId: latestSession
            });
          }
        }
      } catch {
        return NextResponse.json({ 
          success: true,
          checkpoints: []
        });
      }
      
      return NextResponse.json({ 
        success: true,
        checkpoints: []
      });
    }
    
    // Fetch checkpoints for specific session
    const checkpointsBaseDir = path.join(sessionsDir, sessionId, 'checkpoints');
    
    try {
      // Read from both manual/ and auto/ subdirectories + legacy root
      const checkpoints = await readCheckpointsFromAllLocations(checkpointsBaseDir);
      console.log(`📊 Performance: Loaded ${checkpoints.length} checkpoints from all locations for session ${sessionId}`);
      
      // Sort by timestamp (newest first)
      checkpoints.sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime());
      
      return NextResponse.json({ 
        success: true,
        checkpoints,
        sessionId
      });
      
    } catch (error) {
      // Directory doesn't exist or other error
      return NextResponse.json({ 
        success: true,
        checkpoints: [],
        sessionId
      });
    }
    
  } catch (error) {
    console.error('Checkpoint fetch error:', error);
    return NextResponse.json(
      { error: 'Failed to fetch checkpoints' },
      { status: 500 }
    );
  }
}