/**
 * Johnny5 Session Memory Integration Test
 *
 * Tests the full end-to-end pipeline:
 * 1. Index a test checkpoint into memory_chunks
 * 2. Search for it via keyword search
 * 3. Verify query intent routing works
 * 4. Clean up test data
 *
 * Run with: npx tsx __tests__/session-memory-integration.test.ts
 */

import { randomUUID } from 'crypto';

// ============================================================================
// Minimal Test Framework
// ============================================================================

let passed = 0;
let failed = 0;
let total = 0;
const errors: string[] = [];

async function it(name: string, fn: () => Promise<void>) {
  total++;
  try {
    await fn();
    passed++;
    console.log(`  ✅ ${name}`);
  } catch (err: any) {
    failed++;
    const msg = err.message || String(err);
    console.log(`  ❌ ${name}`);
    console.log(`     ${msg}`);
    errors.push(`${name}: ${msg}`);
  }
}

function expect(actual: any) {
  return {
    toBe: (expected: any) => {
      if (actual !== expected) throw new Error(`Expected ${JSON.stringify(actual)} to be ${JSON.stringify(expected)}`);
    },
    toBeGreaterThan: (n: number) => {
      if (!(actual > n)) throw new Error(`Expected ${actual} > ${n}`);
    },
    toBeGreaterThanOrEqual: (n: number) => {
      if (!(actual >= n)) throw new Error(`Expected ${actual} >= ${n}`);
    },
    toBeTruthy: () => {
      if (!actual) throw new Error(`Expected truthy, got ${JSON.stringify(actual)}`);
    },
    toContain: (s: string) => {
      if (typeof actual === 'string' && !actual.includes(s)) throw new Error(`Expected "${actual.substring(0, 80)}..." to contain "${s}"`);
    },
    not: {
      toContain: (s: string) => {
        if (typeof actual === 'string' && actual.includes(s)) throw new Error(`Expected NOT to contain "${s}"`);
      },
    },
  };
}

