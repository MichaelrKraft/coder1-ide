/**
 * Session Data Ingestion Pipeline for Johnny5 Session Memory
 *
 * When a checkpoint is created in the IDE, this module extracts meaningful
 * chunks from the session data and indexes them into the `memory_chunks` table.
 *
 * Source types produced:
 * - ide_session_summary: AI-generated or inferred session summary
 * - ide_terminal_chunk: Terminal output grouped by command
 * - ide_file_change: Files modified during session
 * - ide_error: Errors with surrounding context
 * - ide_git_commit: Git commits during session
 * - ide_command: Commands executed
 *
 * Source ID format: ide:{sessionId}:{chunkType}:{index}
 */

import { randomUUID } from 'crypto';
import {
  upsertMemoryChunk,
  generateContentHash,
  getDb,
} from '@/lib/johnny5-db';

// ============================================================================
// Constants
// ============================================================================

const MAX_TERMINAL_CHUNKS = 20;
const MAX_ERROR_CHUNKS = 10;
const MAX_CHUNKS_PER_SESSION = 50;
const MAX_TOKENS_PER_CHUNK = 500;
const MIN_TERMINAL_LENGTH = 200;

// ============================================================================
// ANSI Code Stripping
// ============================================================================

/**
 * Strip ANSI escape codes from terminal output before indexing.
 * Handles: CSI sequences (colors, cursor), private CSI (?25h),
 * OSC sequences (window titles), and character set selections.
 */
function stripAnsiCodes(text: string): string {
  return text
    .replace(/\x1b\[[0-9;]*[a-zA-Z]/g, '')        // CSI: colors, cursor movement
    .replace(/\x1b\[\?[0-9;]*[a-zA-Z]/g, '')       // Private CSI: ?25h, ?2004h
    .replace(/\x1b\[[<>=]?[0-9;]*[a-zA-Z~]/g, '')  // Extended CSI: mouse, keypad mode
    .replace(/\x1b\][^\x07]*(?:\x07|\x1b\\)/g, '') // OSC: window titles
    .replace(/\x1b\([A-Z]/g, '')                     // Character set selection
    .replace(/[\x00-\x08\x0b\x0c\x0e-\x1f]/g, '') // Control chars (^H, ^G, etc.) except \t \n \r
    .replace(/\r(?!\n)/g, '')                        // Carriage returns (not \r\n)
    .replace(/\^H/g, '')                             // Literal ^H (backspace display)
    .replace(/\^\[\[<[a-z]/g, '');                   // Literal ^[[<u style sequences
}

/**
 * Extract file paths from snapshot files data.
 * Handles JSON-stringified IDEFile[] arrays and plain objects.
 */
function extractFilePathsFromSnapshot(files: any): string[] {
  if (!files) return [];
  try {
    const parsed = typeof files === 'string' ? JSON.parse(files) : files;
    if (Array.isArray(parsed)) {
      return parsed
        .map((f: any) => (typeof f === 'string' ? f : f.path || f.name || ''))
        .filter(Boolean);
    }
    if (typeof parsed === 'object') {
      return Object.keys(parsed);
    }
  } catch {}
  return [];
}

