// Main Export
// ============================================================================

/**
 * Index session data from a checkpoint into memory chunks for semantic search.
 *
 * This is the main entry point for the session data ingestion pipeline.
 * It extracts terminal chunks, file changes, errors, and a session summary
 * from the checkpoint data and upserts them into the `memory_chunks` table.
 *
 * Concurrent calls for the same session are protected by an in-memory lock.
 * Auto-generated checkpoints for already-indexed sessions are skipped.
 *
 * @param checkpoint - The checkpoint data from the IDE
 * @param sessionId - The session identifier
 * @param userId - The user identifier for the memory chunks
 * @returns Object with chunksIndexed and skipped counts
 *
 * @example
 * ```typescript
 * const result = await indexSessionFromCheckpoint(checkpoint, 'session_123', 'user_1');
 * console.log(`Indexed ${result.chunksIndexed} chunks, skipped ${result.skipped}`);
 * ```
 */
export async function indexSessionFromCheckpoint(
  checkpoint: CheckpointData,
  sessionId: string,
  userId: string
): Promise<{ chunksIndexed: number; skipped: number }> {
  // Concurrent indexing protection
  if (indexingLocks.has(sessionId)) {
    console.log(`[SessionIndexer] Session ${sessionId} is already being indexed, skipping`);
    return { chunksIndexed: 0, skipped: 0 };
  }

  indexingLocks.add(sessionId);

  try {
    // Check if session already indexed
    const database = getDb();
    const existingRow = database
      .prepare(`SELECT COUNT(*) as count FROM memory_chunks WHERE source_id LIKE ?`)
      .get(`ide:${sessionId}:%`) as { count: number } | undefined;

    const existingCount = existingRow?.count ?? 0;

    if (existingCount > 0 && checkpoint.autoGenerated) {
      console.log(
        `[SessionIndexer] Session ${sessionId} already indexed (${existingCount} chunks) and checkpoint is auto-generated, skipping`
      );
      return { chunksIndexed: 0, skipped: existingCount };
    }

    // Noise filtering
    if (isNoiseSession(checkpoint)) {
      console.log(`[SessionIndexer] Session ${sessionId} filtered as noise, skipping`);
      return { chunksIndexed: 0, skipped: 0 };
    }

    // Strip ANSI escape codes from terminal history before any processing
    if (checkpoint.terminalHistory) {
      checkpoint = { ...checkpoint, terminalHistory: stripAnsiCodes(checkpoint.terminalHistory) };
    }

    const projectPath = checkpoint.data?.snapshot?.projectPath;
    const projectName = projectPath ? getProjectName(projectPath) : undefined;
    const projectPrefix = projectName ? `[Project: ${projectName}] ` : '';

    let chunksIndexed = 0;

    // ---- Terminal Chunks ----
    if (checkpoint.terminalHistory) {
      const terminalChunks = chunkTerminalHistory(checkpoint.terminalHistory);
      console.log(`[SessionIndexer] Extracted ${terminalChunks.length} terminal chunks`);

      for (let i = 0; i < terminalChunks.length && chunksIndexed < MAX_CHUNKS_PER_SESSION; i++) {
        const chunk = terminalChunks[i];
        const content = redactSensitiveData(`${projectPrefix}${chunk.content}`);
        const contentHash = generateContentHash(content);

        await upsertMemoryChunk({
          id: randomUUID(),
          user_id: userId,
          source_type: 'ide_terminal_chunk',
          source_id: buildSourceId(sessionId, 'terminal', i),
          content,
          content_hash: contentHash,
          token_count: estimateTokens(content),
          heading: chunk.heading,
          section_type: chunk.sectionType,
        });

        chunksIndexed++;
      }
    }

    // ---- Error Chunks ----
    if (checkpoint.terminalHistory) {
      const errorChunks = extractErrors(checkpoint.terminalHistory);
      console.log(`[SessionIndexer] Extracted ${errorChunks.length} error chunks`);

      for (let i = 0; i < errorChunks.length && chunksIndexed < MAX_CHUNKS_PER_SESSION; i++) {
        const chunk = errorChunks[i];
        const content = redactSensitiveData(`${projectPrefix}${chunk.content}`);
        const contentHash = generateContentHash(content);

        await upsertMemoryChunk({
          id: randomUUID(),
          user_id: userId,
          source_type: 'ide_error',
          source_id: buildSourceId(sessionId, 'error', i),
          content,
          content_hash: contentHash,
          token_count: estimateTokens(content),
          heading: chunk.heading,
          section_type: 'error',
        });

        chunksIndexed++;
      }
    }

    // ---- File Change Chunks ----
    // Validate openFiles - detect bad data from Object.keys() on stringified JSON
    let validOpenFiles = checkpoint.openFiles || [];
    if (validOpenFiles.length > 0 && validOpenFiles.every(f => /^\d+$/.test(f))) {
      // All entries are numeric indices — bad data from Object.keys(string)
      validOpenFiles = extractFilePathsFromSnapshot(checkpoint.data?.snapshot?.files);
    }

    if (validOpenFiles.length > 0) {
      console.log(`[SessionIndexer] Indexing ${validOpenFiles.length} file changes`);

      for (let i = 0; i < validOpenFiles.length && chunksIndexed < MAX_CHUNKS_PER_SESSION; i++) {
        const filepath = validOpenFiles[i];
        const filename = filepath.split('/').pop() || filepath;
        const pName = projectName || 'unknown';

        const content = redactSensitiveData(
          `${projectPrefix}File: ${filepath}\nType: open\nProject: ${pName}`
        );
        const contentHash = generateContentHash(content);

        await upsertMemoryChunk({
          id: randomUUID(),
          user_id: userId,
          source_type: 'ide_file_change',
          source_id: buildSourceId(sessionId, 'file', i),
          content,
          content_hash: contentHash,
          token_count: estimateTokens(content),
          heading: filename,
          section_type: 'file_change',
        });

        chunksIndexed++;
      }
    }

    // ---- Session Summary ----
    if (chunksIndexed < MAX_CHUNKS_PER_SESSION) {
      const summaryParts: string[] = [];

      // Timestamp
      try {
        const date = new Date(checkpoint.timestamp);
        summaryParts.push(`Session on ${date.toISOString().split('T')[0]}`);
      } catch {
        summaryParts.push(`Session at ${checkpoint.timestamp}`);
      }

      // Branch
      if (checkpoint.gitBranch) {
        summaryParts.push(`Branch: ${checkpoint.gitBranch}`);
      }

      // Files (use validated openFiles)
      if (validOpenFiles.length > 0) {
        const fileNames = validOpenFiles
          .map((f) => f.split('/').pop() || f)
          .slice(0, 10);
        summaryParts.push(`Files: ${fileNames.join(', ')}`);
      }

      // Activity summary from terminal
      if (checkpoint.terminalHistory) {
        const snippet = checkpoint.terminalHistory.trim().substring(0, 200);
        summaryParts.push(`Activity: ${snippet}`);
      }

      // Session name or description
      if (checkpoint.name) {
        summaryParts.push(`Name: ${checkpoint.name}`);
      }
      if (checkpoint.description) {
        summaryParts.push(`Description: ${checkpoint.description}`);
      }

      const summaryContent = redactSensitiveData(`${projectPrefix}${summaryParts.join('\n')}`);
      const summaryHash = generateContentHash(summaryContent);

      const summaryHeading = checkpoint.name
        || (() => {
          try {
            return `Session ${new Date(checkpoint.timestamp).toISOString().split('T')[0]}`;
          } catch {
            return 'Session Summary';
          }
        })();

      await upsertMemoryChunk({
        id: randomUUID(),
        user_id: userId,
        source_type: 'ide_session_summary',
        source_id: buildSourceId(sessionId, 'summary', 0),
        content: summaryContent,
        content_hash: summaryHash,
        token_count: estimateTokens(summaryContent),
        heading: summaryHeading,
        section_type: 'session_summary',
      });

      chunksIndexed++;
    }

    console.log(
      `[SessionIndexer] Session ${sessionId} indexing complete: ${chunksIndexed} chunks indexed`
    );

    return { chunksIndexed, skipped: 0 };
  } catch (err) {
    console.error(`[SessionIndexer] Error indexing session ${sessionId}:`, err);
    throw err;
  } finally {
    indexingLocks.delete(sessionId);
  }
}
