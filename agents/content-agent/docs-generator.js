const path = require('path');
const fs = require('fs').promises;
const ClaudeAPI = require('../lib/claude-api');

class DocsGenerator {
  constructor() {
    this.claudeAPI = new ClaudeAPI();
    this.docsDir = path.join(__dirname, '../../coder1-ide-next/docs');
    this.queueDir = path.join(__dirname, '../review-queue/pending');
  }

  async generateDocumentation(filePath, docType = 'api') {
    console.log(`📚 Generating ${docType} documentation for: ${filePath}`);

    const code = await this.readFile(filePath);
    const prompt = this.buildDocsPrompt(code, filePath, docType);
    
    try {
      const response = await this.claudeAPI.generateResponse(prompt, {
        model: 'claude-3-haiku-20240307',
        max_tokens: 1500
      });

      return this.formatDocumentation(response, filePath, docType);
    } catch (error) {
      console.error('Error generating docs with Claude:', error.message);
      return this.generateFallbackDocs(code, filePath, docType);
    }
  }

  buildDocsPrompt(code, filePath, docType) {
    return `You are a technical documentation writer for Coder1 IDE.

Generate ${docType} documentation for this code file:

File: ${filePath}

Code:
\`\`\`
${code.substring(0, 3000)}
\`\`\`

Create comprehensive documentation that includes:
${this.getDocTypeInstructions(docType)}

Format as markdown with:
- Clear headings (##, ###)
- Code examples
- Parameter descriptions
- Return value documentation
- Usage examples where appropriate

Be concise but complete.`;
  }

  getDocTypeInstructions(docType) {
    const instructions = {
      'api': `- API endpoint descriptions
- Request/response formats
- Authentication requirements
- Error codes and handling
- Example requests with curl`,
      'component': `- Component purpose and usage
- Props/parameters documentation
- Event handlers
- Styling notes
- Integration examples`,
      'guide': `- Step-by-step instructions
- Prerequisites
- Common pitfalls
- Best practices
- Troubleshooting tips`,
      'reference': `- Function signatures
- Parameter types and descriptions
- Return values
- Exceptions/errors
- Related functions`
    };
    
    return instructions[docType] || instructions['reference'];
  }

  formatDocumentation(content, filePath, docType) {
    const filename = path.basename(filePath, path.extname(filePath));
    const date = new Date().toISOString().split('T')[0];
    
    return `---
title: ${this.generateTitle(filename, docType)}
file: ${filePath}
type: ${docType}
updated: ${date}
status: draft
---

${content}

---

## Related Documentation

- [Getting Started Guide](./guides/getting-started.md)
- [API Reference](./api/README.md)
- [Troubleshooting](./guides/troubleshooting.md)

---

*📚 Documentation auto-generated by Coder1 Docs Generator*
`;
  }

  generateTitle(filename, docType) {
    const formatted = filename
      .replace(/[-_]/g, ' ')
      .replace(/([A-Z])/g, ' $1')
      .trim()
      .split(' ')
      .map(w => w.charAt(0).toUpperCase() + w.slice(1))
      .join(' ');
    
    const typeLabels = {
      'api': 'API Reference',
      'component': 'Component Documentation',
      'guide': 'Guide',
      'reference': 'Reference'
    };
    
    return `${formatted} - ${typeLabels[docType] || 'Documentation'}`;
  }

  async readFile(filePath) {
    try {
      return await fs.readFile(filePath, 'utf8');
    } catch (error) {
      console.error(`Error reading file ${filePath}:`, error.message);
      return '';
    }
  }

  generateFallbackDocs(code, filePath, docType) {
    const filename = path.basename(filePath);
    const date = new Date().toISOString().split('T')[0];
    
    return `---
title: ${this.generateTitle(path.basename(filePath, path.extname(filePath)), docType)}
file: ${filePath}
type: ${docType}
updated: ${date}
status: draft
---

# ${filename}

## Overview

This document provides documentation for \`${filename}\`.

## Purpose

[Description of what this file/module does]

## Usage

\`\`\`javascript
// Import
const module = require('./${filename}');

// Basic usage example
// [Add specific usage examples]
\`\`\`

## API Reference

### Functions

[Document exported functions]

### Parameters

[Document function parameters]

### Return Values

[Document return values]

## Examples

\`\`\`javascript
// Example 1: [Description]
// [Add code example]

// Example 2: [Description]
// [Add code example]
\`\`\`

## Notes

- [Important considerations]
- [Common pitfalls]
- [Best practices]

---

## Related Documentation

- [Getting Started Guide](./guides/getting-started.md)
- [API Reference](./api/README.md)
- [Troubleshooting](./guides/troubleshooting.md)

---

*📚 Documentation auto-generated by Coder1 Docs Generator*
`;
  }

  async detectChangedFiles() {
    try {
      const { exec } = require('child_process');
      const { promisify } = require('util');
      const execAsync = promisify(exec);
      
      const { stdout } = await execAsync('git diff --name-only HEAD~1 HEAD');
      const files = stdout.split('\n').filter(f => f.trim());
      
      const codeFiles = files.filter(f => 
        /\.(js|ts|tsx|jsx)$/.test(f) && 
        !f.includes('node_modules') &&
        !f.includes('.test.')
      );
      
      return codeFiles;
    } catch (error) {
      console.log('⚠️  Could not detect changed files, using empty array');
      return [];
    }
  }

  async updateDocsForChangedFiles() {
    console.log('🔍 Detecting changed files...\n');
    
    const changedFiles = await this.detectChangedFiles();
    
    if (changedFiles.length === 0) {
      console.log('ℹ️  No changed code files detected');
      return {
        updated_at: new Date().toISOString(),
        files_processed: 0,
        docs_generated: []
      };
    }

    console.log(`📝 Found ${changedFiles.length} changed files:\n`);
    changedFiles.forEach((file, i) => {
      console.log(`  ${i + 1}. ${file}`);
    });
    console.log();

    const docs = [];
    
    for (const file of changedFiles.slice(0, 5)) {
      try {
        const fullPath = path.join(__dirname, '../..', file);
        const docType = this.determineDocType(file);
        
        const doc = await this.generateDocumentation(fullPath, docType);
        docs.push({
          source_file: file,
          doc_type: docType,
          content: doc
        });

        console.log(`✅ Generated ${docType} docs for ${file}`);
        
        await new Promise(resolve => setTimeout(resolve, 500));
        
      } catch (error) {
        console.error(`❌ Error processing ${file}:`, error.message);
      }
    }

    return {
      updated_at: new Date().toISOString(),
      files_processed: docs.length,
      docs_generated: docs
    };
  }

  determineDocType(filePath) {
    if (filePath.includes('/api/')) return 'api';
    if (filePath.includes('/components/')) return 'component';
    if (filePath.includes('/guides/')) return 'guide';
    return 'reference';
  }

  async saveToReviewQueue(doc, queueId) {
    await fs.mkdir(this.queueDir, { recursive: true });
    
    const queueItem = {
      id: queueId,
      type: 'documentation',
      source_file: doc.source_file,
      doc_type: doc.doc_type,
      content: doc.content,
      created_at: new Date().toISOString(),
      status: 'pending_review'
    };

    const filepath = path.join(this.queueDir, `docs-${queueId}.json`);
    await fs.writeFile(filepath, JSON.stringify(queueItem, null, 2));
    
    console.log(`📋 Saved to review queue: ${filepath}`);
    return filepath;
  }

  async saveBatchToQueue(results) {
    const saved = [];
    
    for (let i = 0; i < results.docs_generated.length; i++) {
      const doc = results.docs_generated[i];
      const queueId = `${Date.now()}-${i}`;
      const filepath = await this.saveToReviewQueue(doc, queueId);
      saved.push({ queueId, filepath, source_file: doc.source_file });
    }

    return saved;
  }
}

async function main() {
  const generator = new DocsGenerator();
  
  try {
    console.log('🚀 Starting documentation generation...\n');
    
    const results = await generator.updateDocsForChangedFiles();
    
    console.log(`\n✅ Processed ${results.files_processed} files`);
    
    if (results.docs_generated.length > 0) {
      console.log('\n📋 Saving to review queue...');
      const saved = await generator.saveBatchToQueue(results);
      
      console.log(`\n✅ Saved ${saved.length} documentation updates to review queue`);
    }
    
  } catch (error) {
    console.error('\n❌ Error:', error.message);
    console.error(error.stack);
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}

module.exports = DocsGenerator;
